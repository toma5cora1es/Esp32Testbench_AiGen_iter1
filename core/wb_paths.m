function out = wb_paths(kind, name)
%WB_PATHS Dynamic path resolver for the ESP32 Workbench (zero hardcoded paths).
    rootEnv = getenv('ESP32_WB_ROOT');
    if ~isempty(rootEnv) && isfolder(rootEnv)
        rootDir = rootEnv;
    else
        rootDir = fileparts(fileparts(mfilename('fullpath')));
    end

    p = struct( ...
        'root',          rootDir, ...
        'config',        fullfile(rootDir, 'config'), ...
        'core',          fullfile(rootDir, 'core'), ...
        'instruments',   fullfile(rootDir, 'instruments'), ...
        'ui',            fullfile(rootDir, 'ui'), ...
        'testsequences', fullfile(rootDir, 'testsequences'), ...
        'firmware',      fullfile(rootDir, 'firmware'), ...
        'daemon',        fullfile(rootDir, 'firmware', 'core0_daemon'), ...
        'sketches',      fullfile(rootDir, 'firmware', 'sketches'), ...
        'databases',     fullfile(rootDir, 'databases'), ...
        'results',       fullfile(rootDir, 'results'), ...
        'sfrDb',         fullfile(rootDir, 'databases', 'esp32_sfr.json'), ...
        'hwCalDb',       fullfile(rootDir, 'databases', 'esp32_hw_cal.json'), ...
        'buildTemp',     fullfile(tempdir, 'esp32_workbench_build'));

    if nargin == 0 || isempty(kind)
        out = p; return;
    end

    switch lower(strtrim(char(kind)))
        case 'sketch'
            sName = strtrim(char(name));
            candidate = fullfile(p.sketches, sName, [sName '.ino']);
            if isfile(candidate), out = candidate; else, out = sName; end
        case 'results_suite'
            suiteDir = fullfile(p.results, strtrim(char(name)));
            if ~isfolder(suiteDir), mkdir(suiteDir); end
            out = suiteDir;
        otherwise
            if isfield(p, kind), out = p.(kind);
            else, error('WB:UnknownPathKind', 'Unknown path kind: %s', kind);
            end
    end
end